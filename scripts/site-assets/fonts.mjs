// Copies the site's web fonts from their pinned npm packages into assets/fonts/ and writes the
// @font-face rules to assets/css/fonts.css. The fonts are served from the site itself, so a page
// contacts no font service. Run from this directory: npm ci && npm run fonts
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fontsDir = join(here, '../../assets/fonts');
const cssFile = join(here, '../../assets/css/fonts.css');

// latin-ext carries the Hungarian ő and ű; a browser fetches a subset only when a page uses it.
const SUBSETS = ['latin', 'latin-ext'];
const FAMILIES = [
  { slug: 'playfair-display', faces: [[400, 'normal'], [400, 'italic'], [500, 'normal'], [500, 'italic']] },
  { slug: 'ibm-plex-sans', faces: [[400, 'normal'], [500, 'normal'], [600, 'normal']] },
  { slug: 'ibm-plex-mono', faces: [[400, 'normal'], [500, 'normal']] },
];

function fontFace(slug, subset, weight, style) {
  const source = join(here, 'node_modules/@fontsource', slug, `${weight}${style === 'italic' ? '-italic' : ''}.css`);
  const name = `${slug}-${subset}-${weight}-${style}`;
  const block = readFileSync(source, 'utf8').split('/* ').find((part) => part.startsWith(`${name} */`));
  if (block === undefined) {
    throw new Error(`${source}: no @font-face for ${name}`);
  }
  const rule = block.slice(block.indexOf('@font-face')).trim();
  const src = `src: url(../fonts/${name}.woff2) format('woff2');`;
  const rewritten = rule.replace(/src: [^;]+;/, src);
  if (!rewritten.includes(src) || !rewritten.includes('unicode-range:')) {
    throw new Error(`${source}: unexpected @font-face for ${name}`);
  }
  const file = join(dirname(source), 'files', `${name}.woff2`);
  if (!existsSync(file)) {
    throw new Error(`${file}: missing`);
  }
  return { name, rule: rewritten, file };
}

// Everything is resolved first, so a missing face leaves the committed files as they were.
const faces = FAMILIES.flatMap(({ slug, faces: list }) =>
  list.flatMap(([weight, style]) => SUBSETS.map((subset) => fontFace(slug, subset, weight, style))));

mkdirSync(fontsDir, { recursive: true });
for (const { name, file } of faces) {
  copyFileSync(file, join(fontsDir, `${name}.woff2`));
}
// SIL OFL 1.1: the licence travels with every copy of the fonts.
for (const { slug } of FAMILIES) {
  copyFileSync(join(here, 'node_modules/@fontsource', slug, 'LICENSE'), join(fontsDir, `LICENSE-${slug}.txt`));
}
const header = '/* Generated by scripts/site-assets/fonts.mjs from the @fontsource packages it pins. Do not edit.\n'
  + '   Playfair Display and IBM Plex are licensed under the SIL Open Font License 1.1: see /assets/fonts/. */\n';
writeFileSync(cssFile, header + faces.map(({ rule }) => rule).join('\n') + '\n');
console.log(`${faces.length} font files, ${FAMILIES.length} licences, assets/css/fonts.css`);
