#!/usr/bin/env python3
"""Check built canonical URLs, bilingual privacy metadata, publication policy, drawing colours,
the resources pages load and their link-preview images."""
import argparse
from html.parser import HTMLParser
import json
import os
from pathlib import Path
import re
from urllib.parse import unquote, urljoin, urlsplit
import xml.etree.ElementTree as ET


class Page(HTMLParser):
    def __init__(self, path):
        super().__init__()
        self.lang = None
        self.canonicals = []
        self.alternates = {}
        self.robots = None
        self.description = None
        self.preview = None
        self.beacons = 0
        self.feed(path.read_text(encoding='utf-8'))

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'html':
            self.lang = attrs.get('lang')
        if tag == 'link':
            if attrs.get('rel') == 'canonical':
                self.canonicals.append(attrs.get('href'))
            if attrs.get('rel') == 'alternate' and 'hreflang' in attrs:
                self.alternates[attrs['hreflang']] = attrs.get('href')
        if tag == 'meta' and attrs.get('name') == 'robots':
            self.robots = attrs.get('content')
        if tag == 'meta' and attrs.get('name') == 'description':
            self.description = attrs.get('content')
        if tag == 'meta' and attrs.get('property') == 'og:image':
            self.preview = attrs.get('content')
        if tag == 'script' and attrs.get('src') == 'https://static.cloudflareinsights.com/beacon.min.js':
            self.beacons += 1


# The origins built pages load resources from. Each new origin is a new recipient of readers'
# data: it needs an entry in scripts/privacy-site.json, and a review, before it is added here.
LOADED_ORIGINS = {
    'https://static.cloudflareinsights.com',
}
# Attributes through which an element loads a resource. A <link> loads its href unless every one of
# its link types only names a page or a person.
LOAD_ATTRIBUTES = {
    'script': ('src',), 'img': ('src', 'srcset'), 'source': ('src', 'srcset'), 'iframe': ('src',),
    'video': ('src', 'poster'), 'audio': ('src',), 'track': ('src',), 'embed': ('src',),
    'object': ('data',), 'input': ('src',),
}
REFERENCE_LINK_TYPES = {'canonical', 'alternate', 'author', 'license', 'me', 'next', 'prev', 'search', 'shortlink'}


def url_value(value):
    """An attribute value as a browser reads it as a URL: tabs and line breaks removed, spaces trimmed."""
    return re.sub(r'[\t\n\r]', '', value or '').strip()


class Resources(HTMLParser):
    """The URLs a page loads, as written in its markup."""
    def __init__(self, html):
        super().__init__()
        self.urls = []
        self.feed(html)

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'link' and 'href' in attrs and not set((attrs.get('rel') or '').lower().split()) <= REFERENCE_LINK_TYPES:
            self.urls.append(url_value(attrs['href']))
        for name in LOAD_ATTRIBUTES.get(tag, ()):
            if name == 'srcset' and name in attrs:
                self.urls.extend(candidate.split()[0] for candidate in (attrs[name] or '').split(',') if candidate.strip())
            elif name in attrs:
                self.urls.append(url_value(attrs[name]))


def check_page_loads(name, html, files):
    """Every resource the page loads comes from a listed origin, or is one of the site's files."""
    for url in Resources(html).urls:
        assert url, f'{name}: loads an empty URL'
        parts = urlsplit(url)
        if parts.netloc:
            origin = (parts.scheme or 'https') + '://' + parts.netloc.lower()
            assert origin in LOADED_ORIGINS, f'{name}: loads {url} from an origin with no privacy entry'
        elif parts.scheme in ('', 'http', 'https') and parts.path:
            path = unquote(urlsplit(urljoin('/' + name, url)).path)
            assert (path + 'index.html' if path.endswith('/') else path) in files, f'{name}: missing local target {url}'


def check_preview(name, preview, files, origin):
    """Every page has a link-preview image, and it is one of the site's own files."""
    assert preview, f'{name}: no link-preview image'
    assert preview.startswith(origin + '/'), f'{name}: link-preview image {preview} is not an absolute URL on this site'
    assert unquote(urlsplit(preview).path) in files, f'{name}: missing link-preview image {preview}'


def check_loads(root, origin):
    root = Path(root)
    files = {'/' + path.relative_to(root).as_posix() for path in root.rglob('*') if path.is_file()}
    for path in sorted(root.rglob('*.html')):
        name = path.relative_to(root).as_posix()
        check_page_loads(name, path.read_text(encoding='utf-8'), files)
        check_preview(name, Page(path).preview, files, origin)


# Every drawing is generated by scripts/site-assets/render.mjs, in palette colours that its <style>
# repaints for light and dark mode. Only the chart examples also keep the library's series colours.
SERIES_COLOURS = 'assets/images/projects/'
PALETTE = Path(__file__).resolve().parent.parent / '_data' / 'palette.json'
SVG = '{http://www.w3.org/2000/svg}'
DARK = re.compile(r'@media\s*\(prefers-color-scheme:\s*dark\)')


def declared_colours(css):
    return {name: value.strip() for name, value in re.findall(r'--([a-z0-9-]+)\s*:\s*([^;}]*)', css)}


def check_palette(palette):
    assert palette['light'].keys() == palette['dark'].keys(), '_data/palette.json: light and dark must name the same colours'


def check_drawing(name, svg, palette):
    drawing = ET.fromstring(svg)
    styles = list(drawing.iter(SVG + 'style'))
    assert styles, name + ': drawing has no light and dark theme'
    css = ''.join(style.text or '' for style in styles).lower()
    light, dark = (DARK.split(css, maxsplit=1) + [''])[:2]
    theme = {'light': declared_colours(light), 'dark': declared_colours(dark)}
    assert theme['light'] and theme['light'].keys() == theme['dark'].keys(), \
        name + ': theme must declare the same colours for light and dark mode'
    for mode in ('light', 'dark'):
        stale = {key: value for key, value in theme[mode].items() if palette[mode].get(key, '').lower() != value}
        assert not stale, f'{name}: {mode} colours differ from _data/palette.json: {stale}'
    literal = [paint.strip() for paint in re.findall(r'(?<![-\w])(?:fill|stroke)\s*:\s*([^;}]+)', css)
               if paint.strip() != 'none' and not paint.strip().startswith('var(')]
    assert not literal, f'{name}: theme paints a colour that is not a palette colour: {literal}'
    undeclared = set(re.findall(r'var\(--([a-z0-9-]+)\)', css)) - theme['light'].keys()
    assert not undeclared, f'{name}: theme uses colours it does not declare: {sorted(undeclared)}'
    if not name.startswith(SERIES_COLOURS):
        repainted = set(re.findall(r'\[(fill|stroke)="([^"]+)"\]', css))
        drawn = {(attribute, element.get(attribute).lower()) for element in drawing.iter() for attribute in ('fill', 'stroke')
                 if element.get(attribute) and element.get(attribute) != 'none'}
        unrepainted = sorted(f'{attribute}={value}' for attribute, value in drawn - repainted)
        assert not unrepainted, f'{name}: colours the theme does not repaint: {unrepainted}'


def check_drawings(root, palette):
    root = Path(root)
    for path in sorted((root / 'assets/images').rglob('*.svg')):
        check_drawing(path.relative_to(root).as_posix(), path.read_text(encoding='utf-8'), palette)


def check(root, published, origin):
    root = Path(root)
    origin = origin.rstrip('/')
    home = Page(root / 'index.html')
    assert home.canonicals == [origin + '/'], 'Homepage canonical does not match the site root'
    urls = [item.text for item in ET.parse(root / 'sitemap.xml').iter('{http://www.sitemaps.org/schemas/sitemap/0.9}loc')]
    assert len(urls) == len(set(urls)), 'Duplicate sitemap URLs'
    assert origin + '/' in urls, 'Homepage is missing from sitemap'
    for url in urls:
        assert url.startswith(origin + '/'), 'Sitemap contains another origin'
        path = urlsplit(url).path
        assert '//' not in path, 'Sitemap contains a doubled slash'
        assert path != '/404.html', '404 page must not be in sitemap'
        target = root / path.lstrip('/')
        if path.endswith('/'):
            target /= 'index.html'
        assert target.is_file(), 'Sitemap points to a missing file: ' + path
    for language in ('en',):
        for kind in ('privacy', 'choices'):
            path = '/privacy/' + language + '/' + kind + '.html'
            page = Page(root / path.lstrip('/'))
            assert page.lang == language, 'Document language does not match content'
            assert page.canonicals == [origin + path], 'Privacy canonical mismatch'
            expected = {lang: origin + '/privacy/' + lang + '/' + kind + '.html' for lang in ('en',)}
            assert page.alternates == expected, 'Language alternates must include self and counterpart'
            assert page.description, 'Missing privacy description'
            assert page.robots == ('index,follow' if published else 'noindex,nofollow'), 'Wrong privacy indexing policy'
            assert ((origin + path) in urls) == published, 'Sitemap disagrees with privacy publication status'
            assert page.beacons == 0, 'Privacy pages must not load analytics'
    assert 'Sitemap: ' + origin + '/sitemap.xml' in (root / 'robots.txt').read_text(encoding='utf-8')
    assert Page(root / '404.html').robots == 'noindex,follow'
    for name in ('scripts', 'docs', 'ANALYTICS.md'):
        assert not (root / name).exists(), 'Non-site material included in output: ' + name
    palette = json.loads(PALETTE.read_text(encoding='utf-8'))
    check_palette(palette)
    check_drawings(root, palette)
    check_loads(root, origin)
    print('Built website: canonical URLs, language alternates, sitemap, robots, privacy analytics policy,'
          ' drawing colours, loaded origins, local targets and link-preview images passed')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    config = json.loads(Path(__file__).with_name('privacy-site.json').read_text(encoding='utf-8'))
    check(args.output, os.environ.get('PRIVACY_PUBLISH') == 'true', config['site_url'])
